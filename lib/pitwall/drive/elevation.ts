/** ความสูงที่สัดส่วน f ของรอบ (โค้งเรียบผ่านทุกจุดควบคุม วนรอบ) */
export function elevationAt(id: string, f: number, seed: number): number {
  const pts = ELEVATION[id];
  if (!pts) {
    // เนินเตี้ย ๆ ไม่เกิน ~2 ม. (ไม่มีสนามไหนราบเป๊ะ)
    const a = seed * 0.37;
    return 1.2 * Math.sin(2 * Math.PI * f + a) + 0.7 * Math.sin(6 * Math.PI * f + a * 2.3);
  }
  const u = ((f % 1) + 1) % 1;
  let k = pts.length - 1;
  for (let i = 0; i < pts.length; i++) if (pts[i][0] <= u) k = i;
  const n = pts.length;
  const h = (i: number) => pts[((i % n) + n) % n][1];
  const f0 = pts[k][0];
  const f1raw = pts[(k + 1) % n][0];
  const f1 = f1raw <= f0 ? f1raw + 1 : f1raw;
  const t = (u - f0) / Math.max(1e-6, f1 - f0);
  // Catmull-Rom
  const [a, b, c, d] = [h(k - 1), h(k), h(k + 1), h(k + 2)];
  return 0.5 * (2 * b + (-a + c) * t + (2 * a - 5 * b + 4 * c - d) * t * t + (-a + 3 * b - 3 * c + d) * t * t * t);
}
