/** ความสูงที่ระยะ s เมตร (โค้งเรียบผ่านทุกจุดควบคุม วนรอบที่ length) */
export function elevationAt(id: string, s: number, length: number, seed: number): number {
  const pts = ELEVATION[id];
  const f = s / length;
  if (!pts) {
    // เนินเตี้ย ๆ ไม่เกิน ~2 ม. (ไม่มีสนามไหนราบเป๊ะ)
    const a = seed * 0.37;
    return 1.2 * Math.sin(2 * Math.PI * f + a) + 0.7 * Math.sin(6 * Math.PI * f + a * 2.3);
  }
  const u = ((s % length) + length) % length;
  const n = pts.length;
  let k = n - 1;
  for (let i = 0; i < n; i++) if (pts[i][0] <= u) k = i;
  const h = (i: number) => pts[((i % n) + n) % n][1];
  const s0 = pts[k][0];
  const s1raw = pts[(k + 1) % n][0];
  const s1 = s1raw <= s0 ? s1raw + length : s1raw;
  const t = (u - s0) / Math.max(1e-6, s1 - s0);
  // Catmull-Rom
  const [a, b, c, d] = [h(k - 1), h(k), h(k + 1), h(k + 2)];
  return 0.5 * (2 * b + (-a + c) * t + (2 * a - 5 * b + 4 * c - d) * t * t + (-a + 3 * b - 3 * c + d) * t * t * t);
}
